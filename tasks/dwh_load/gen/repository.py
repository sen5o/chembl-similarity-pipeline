"""IO boundary for dwh_load: S3 read, staging read, core write.

The mart is small (~560 facts, a few hundred dimension rows), so plain INSERTs
are used rather than COPY — COPY earns its complexity at millions of rows, not
hundreds. Everything happens in one transaction: dimension first (it generates
the surrogate keys), then facts referencing them.
"""

from __future__ import annotations

import io
import logging

import boto3
import pyarrow.parquet as pq

log = logging.getLogger("dwh_load")


# --- reads -----------------------------------------------------------------


def read_top10(bucket: str, key: str) -> list[dict]:
    """The top-10 table from similarity_computation (one row per source/target)."""
    body = boto3.client("s3").get_object(Bucket=bucket, Key=key)["Body"].read()
    rows = pq.read_table(io.BytesIO(body)).to_pylist()
    log.info("Read %s top-10 rows from s3://%s/%s", len(rows), bucket, key)
    return rows


# Properties for the molecules that appear in facts. Joined from the two
# staging tables that carry them; molecules with no properties row still get a
# dimension row (LEFT JOIN) rather than being dropped from the mart.
_PROPERTIES_SQL = """
    SELECT
        md.chembl_id,
        md.molecule_type,
        cp.mw_freebase,
        cp.alogp,
        cp.psa,
        cp.cx_logp,
        cp.molecular_species,
        cp.full_mwt,
        cp.aromatic_rings,
        cp.heavy_atoms
    FROM staging.molecule_dictionary md
    LEFT JOIN staging.compound_properties cp ON cp.molregno = md.molregno
    WHERE md.chembl_id = ANY(%(chembl_ids)s)
"""


def fetch_molecule_properties(dsn: str, chembl_ids: list[str]) -> list[dict]:
    """Look up the 10 brief-required attributes for the given molecules."""
    import psycopg2
    import psycopg2.extras

    conn = psycopg2.connect(dsn)
    try:
        with conn, conn.cursor(cursor_factory=psycopg2.extras.RealDictCursor) as cur:
            cur.execute(_PROPERTIES_SQL, {"chembl_ids": chembl_ids})
            rows = [dict(r) for r in cur.fetchall()]
    finally:
        conn.close()
    log.info("Fetched properties for %s/%s molecules", len(rows), len(chembl_ids))
    return rows


# --- write -----------------------------------------------------------------

_DIM_COLUMNS = (
    "chembl_id",
    "molecule_type",
    "mw_freebase",
    "alogp",
    "psa",
    "cx_logp",
    "molecular_species",
    "full_mwt",
    "aromatic_rings",
    "heavy_atoms",
)


def load_star_schema(dsn: str, dim_rows: list[dict], fact_rows: list[dict]) -> tuple[int, int]:
    """Full refresh of the mart in a single transaction.

    `fact_rows` carry source/target as chembl_id; they are resolved to surrogate
    keys against the dimension inserted moments earlier in the same transaction,
    so the mart is never half-loaded and facts can never point at a stale key.

    Returns (dim_count, fact_count).
    """
    import psycopg2
    import psycopg2.extras

    conn = psycopg2.connect(dsn)
    try:
        with conn, conn.cursor() as cur:
            # Both tables together: fact references dim, so they must be
            # emptied in one statement (or with CASCADE) to satisfy the FK.
            cur.execute("TRUNCATE core.fact_similarity, core.dim_molecule RESTART IDENTITY")

            psycopg2.extras.execute_values(
                cur,
                f"INSERT INTO core.dim_molecule ({', '.join(_DIM_COLUMNS)}) VALUES %s",
                [tuple(row.get(c) for c in _DIM_COLUMNS) for row in dim_rows],
            )

            # surrogate keys generated by the insert above
            cur.execute("SELECT chembl_id, molecule_key FROM core.dim_molecule")
            key_of = dict(cur.fetchall())

            psycopg2.extras.execute_values(
                cur,
                """
                INSERT INTO core.fact_similarity (
                    source_molecule_key, target_molecule_key,
                    tanimoto_score, has_duplicates_of_last_largest_score
                ) VALUES %s
                """,
                [
                    (
                        key_of[f["source_chembl_id"]],
                        key_of[f["target_chembl_id"]],
                        f["tanimoto_score"],
                        f["has_duplicates_of_last_largest_score"],
                    )
                    for f in fact_rows
                ],
            )
            cur.execute("SELECT count(*) FROM core.dim_molecule")
            dim_count = cur.fetchone()[0]
            cur.execute("SELECT count(*) FROM core.fact_similarity")
            fact_count = cur.fetchone()[0]
        # `with conn` commits here; any exception above rolls the whole load back
    finally:
        conn.close()

    log.info("Loaded core: %s dimension rows, %s facts", dim_count, fact_count)
    return dim_count, fact_count
